#!/usr/bin/env python3
"""Synthesise the body impulse responses for the strings beta.

Per family (violin, viola, cello, bass) one 1024-tap IR at 47619 Hz (21.5 ms)
with what a real body does above its lowest resonances:
  - the direct (bridge) sound,
  - the smooth bridge-hill / mid / upper resonances,
  - a dense field of body modes (density rising with frequency, damping
    rising with frequency, random strengths and signs), which gives the
    irregular peaks and dips of a measured body response.
The long-ringing low modes (air A0, wood B1-, B1+) stay as IIR resonators in
the engine, because 21 ms would cut them off. Writes strings_body_ir.h.
"""
import numpy as np, sys

SR, N = 47619, 1024
# same table as STR_BODY in strings_engine.h: (Hz, Q, gain) per family
BODY = [
  [(275,15,.9),(470,25,1.3),(550,25,1.2),(1000,6,.5),(2500,2.5,1.0),(3300,5,.4)],
  [(230,14,.9),(350,22,1.3),(430,22,1.2),(850,6,.5),(2000,2.5,.9),(2700,5,.35)],
  [(100,12,1.),(145,20,1.3),(205,20,1.2),(400,6,.5),(1300,2.5,.7),(2000,5,.3)],
  [(58,10,1.1),(95,16,1.2),(125,16,1.),(250,6,.5),(800,2.5,.5),(1300,5,.2)],
]
SEEDS = [1348, 1221, 1266, 1323]   # picked for an even note-to-note level
DIRECT = [.35, .4, .45, .5]
TOP = [5500, 4500, 3500, 2000]

def mode_ir(hz, q, gain, n=N):
    """impulse response of strMode() in the engine"""
    w = 2*np.pi*hz/SR; r = np.exp(-np.pi*hz/(q*SR))
    g = gain*(1-r)*2*np.sin(w)
    k = np.arange(n)
    return g * r**k * np.sin((k+1)*w)/np.sin(w)

def make(fam, seed):
    rng = np.random.default_rng(seed)
    t = np.arange(N)/SR
    smooth = np.zeros(N); smooth[0] = DIRECT[fam]
    for hz, q, g in BODY[fam][3:]:
        smooth += mode_ir(hz, q, g)
    # envelope of the dense modes follows the smooth response (bridge hill)
    f = np.fft.rfftfreq(8192, 1/SR); H = np.abs(np.fft.rfft(smooth, 8192))
    env = lambda hz: np.interp(hz, f, H)
    f0 = 1.35*BODY[fam][2][0]                    # just above B1+
    f1 = min(1.6*TOP[fam], 9000)
    dense = np.zeros(N); hz = f0; n = 0
    while hz < f1:
        spacing = 0.075*hz**0.75                 # modes get denser up high
        hz += spacing*(0.4 + 1.2*rng.random())
        q = 32*(hz/1000)**-0.25                  # more damping up high
        q = min(q, np.pi*hz*0.006)               # ring out well inside the IR
        a = env(hz)*np.exp(rng.normal(0, 0.55))*(1 if rng.random() < .5 else -1)
        a *= 1/(1+(hz/(1.3*TOP[fam]))**4)        # body radiates little up top
        ph = rng.random()*2*np.pi
        dense += a*np.exp(-np.pi*hz*t/q)*np.sin(2*np.pi*hz*t+ph)*(np.pi*hz/q)/SR*2
        n += 1
    dense *= np.sqrt(np.sum(smooth[1:]**2)/np.sum(dense**2))   # same energy as the smooth part
    ir = 0.75*smooth + 0.9*dense
    fade = np.ones(N); L = 192
    fade[-L:] = 0.5+0.5*np.cos(np.linspace(0, np.pi, L))
    ir *= fade
    return ir*level_match(fam, ir), n

def level_match(fam, ir):
    """scale the IR so a bowed-string-like tone (sawtooth) through
    low modes + IR is as loud as through the old modal body"""
    from scipy.signal import lfilter
    K = 1-np.exp(-2*np.pi*TOP[fam]/SR)
    lp = lambda x: lfilter([K], [1, -(1-K)], x)
    def modes(x, ms):
        y = np.zeros_like(x)
        for hz, q, g in ms:
            w = 2*np.pi*hz/SR; r = np.exp(-np.pi*hz/(q*SR))
            y += lfilter([g*(1-r)*2*np.sin(w)], [1, -2*r*np.cos(w), r*r], x)
        return y
    low0 = {0: 196, 1: 131, 2: 65.4, 3: 41.2}[fam]
    A = B = C = 0.0
    for semis in range(0, 30, 4):
        hz = low0*2**(semis/12); n = np.arange(int(0.4*SR))
        x = 2*((n*hz/SR) % 1)-1; x -= x.mean()
        old = lp(modes(x, BODY[fam]) + DIRECT[fam]*x)
        low = modes(x, BODY[fam][:3]); hi = np.convolve(lp(x), ir)[:len(x)]
        sl = slice(len(x)//2, None)
        A += np.sum(hi[sl]**2); B += 2*np.sum(hi[sl]*low[sl]); C += np.sum(low[sl]**2) - np.sum(old[sl]**2)
    g = (-B + np.sqrt(max(B*B-4*A*C, 0)))/(2*A)
    print(f"  level match gain {g:.3f}", file=sys.stderr)
    return g

out = ["// generated by tools/make_body_ir.py: body impulse responses (47619 Hz, 1024 taps)",
       "// above the low IIR modes (A0, B1-, B1+): direct sound, bridge hill and a dense",
       "// field of body modes. Order: violin, viola, cello, bass.",
       "#pragma once", "static const float STR_BODY_IR[4][1024] = {"]
for fam, name in enumerate(["violin", "viola", "cello", "bass"]):
    ir, n = make(fam, SEEDS[fam])
    print(f"{name}: {n} modes, peak {np.abs(ir).max():.3f}", file=sys.stderr)
    out.append("  { // " + name)
    for i in range(0, N, 8):
        out.append("    " + ", ".join(f"{x:.7e}f" for x in ir[i:i+8]) + ",")
    out.append("  },")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
